create table if not exists public.user_roles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('admin', 'customer')),
  created_at timestamptz not null default now()
);

alter table public.user_roles enable row level security;

-- Signed-in users may read only their own role. No client-side role writes are allowed.
drop policy if exists "Users can read their own role" on public.user_roles;
create policy "Users can read their own role"
on public.user_roles for select
to authenticated
using (auth.uid() = user_id);

-- Create the owner role only if the account exists.
insert into public.user_roles (user_id, role)
select id, 'admin'
from auth.users
where lower(email) = lower('jikzoboyrsa0@gmail.com')
on conflict (user_id) do update set role = 'admin';

create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  service text,
  message text not null check (char_length(message) between 1 and 5000),
  status text not null default 'new' check (status in ('new', 'in progress', 'completed')),
  created_at timestamptz not null default now()
);

alter table public.enquiries enable row level security;

-- Visitors can submit an enquiry, but cannot read other people's enquiries.
drop policy if exists "Anyone can submit an enquiry" on public.enquiries;
create policy "Anyone can submit an enquiry"
on public.enquiries for insert
to anon, authenticated
with check (
  char_length(name) between 1 and 120
  and char_length(email) between 3 and 254
  and char_length(message) between 1 and 5000
);

-- Only accounts explicitly assigned the admin role can read enquiries.
drop policy if exists "Admins can read enquiries" on public.enquiries;
create policy "Admins can read enquiries"
on public.enquiries for select
to authenticated
using (
  exists (
    select 1 from public.user_roles
    where user_roles.user_id = auth.uid()
      and user_roles.role = 'admin'
  )
);

grant select on public.user_roles to authenticated;
grant insert on public.enquiries to anon, authenticated;
grant select on public.enquiries to authenticated;
grant usage, select on sequence public.enquiries_id_seq to anon, authenticated;
