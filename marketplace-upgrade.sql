create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  display_name text not null check (char_length(display_name) between 1 and 80),
  rating integer not null check (rating between 1 and 5),
  body text not null check (char_length(body) between 10 and 1000),
  approved boolean not null default false,
  created_at timestamptz not null default now()
);
alter table public.reviews enable row level security;
revoke all on table public.reviews from anon, authenticated;
grant select, insert on table public.reviews to anon, authenticated;
grant update, delete on table public.reviews to authenticated;
grant usage, select on sequence public.reviews_id_seq to anon, authenticated;
drop policy if exists "Public read approved reviews" on public.reviews;
create policy "Public read approved reviews" on public.reviews for select to anon, authenticated
using (approved = true or exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'));
drop policy if exists "Visitors submit unapproved reviews" on public.reviews;
create policy "Visitors submit unapproved reviews" on public.reviews for insert to anon, authenticated
with check (approved = false);
drop policy if exists "Admins moderate reviews" on public.reviews;
create policy "Admins moderate reviews" on public.reviews for update to authenticated
using (exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'))
with check (exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'));
drop policy if exists "Admins delete reviews" on public.reviews;
create policy "Admins delete reviews" on public.reviews for delete to authenticated
using (exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'));
