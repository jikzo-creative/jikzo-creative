create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  service text not null check (char_length(service) between 1 and 120),
  brief text not null check (char_length(brief) between 10 and 3000),
  status text not null default 'pending' check (status in ('pending','reviewing','quoted','in_progress','completed','cancelled')),
  admin_note text not null default '' check (char_length(admin_note) <= 2000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.orders enable row level security;
revoke all on table public.orders from anon, authenticated;
grant select, insert on table public.orders to authenticated;
grant update (status, admin_note, updated_at) on table public.orders to authenticated;
grant usage, select on sequence public.orders_id_seq to authenticated;

drop policy if exists "Customers view own orders and admins view all" on public.orders;
create policy "Customers view own orders and admins view all" on public.orders for select to authenticated
using (user_id = (select auth.uid()) or exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'));
drop policy if exists "Customers create own orders" on public.orders;
create policy "Customers create own orders" on public.orders for insert to authenticated
with check (user_id = (select auth.uid()));
drop policy if exists "Admins update orders" on public.orders;
create policy "Admins update orders" on public.orders for update to authenticated
using (exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'))
with check (exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'));
create index if not exists orders_user_created_idx on public.orders(user_id, created_at desc);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  title text not null,
  description text not null default '',
  image_url text not null default '',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.services enable row level security;
revoke all on table public.services from anon, authenticated;
grant select on table public.services to anon, authenticated;
grant insert, update, delete on table public.services to authenticated;
drop policy if exists "Public view active services" on public.services;
create policy "Public view active services" on public.services for select to anon, authenticated
using (active = true or exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'));
drop policy if exists "Admins manage services" on public.services;
create policy "Admins manage services" on public.services for all to authenticated
using (exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'))
with check (exists (select 1 from public.user_roles r where r.user_id = (select auth.uid()) and r.role = 'admin'));
